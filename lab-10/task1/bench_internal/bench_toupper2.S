#
# Функция на языке ассемблера для конвертации символов
# строкового литерала в верхний регистр
#
# a1 - адрес выходного строкового литерала
# a0 - адрес входного строкового литерала
# t2 - текущий обрабатываемый символ
# t3 - временный регистр для сравнения
# t4 - минус 'a' для сравнения < 26
# t5 - исходная строка для расчета ее длины
#
.global bench_toupper2               # Разрешить другим файлам вызывать подпрограмму
bench_toupper2:
    mv t5, a1            # сохранить исходную outstr для расчета длины

# Цикл выполняется до тех пор,
# пока не встретится нулевой (null) символ
loop:
    lb t2, 0(a0)        # загрузить символ
    addi a0, a0, 1      # увеличить указатель буфера на 1

    # Нужно проверить, что 'a' <= t2 <= 'z'
    # Для этого сначала вычтем 'a'
    addi t4, t2, -'a'
    # Если t4 >= 26, перейти в end if
    li t3, 26           # загрузить 'z'-'a' для сравнения
    bltu t3, t4, cont        # перейти в конец, если не в нижнем регистре

    # если программа выполнилась до этого места,
    # то буква в нижнем регистре, поэтому конвертировать ее
    addi t2, t2, ('A'-'a')
cont:                    # end if
    sb t2, 0(a1)        # сохранить символ в выходном строковом литерале
    addi a1, a1, 1      # увеличить буфер на 1 для следующего символа

    li t3, 0           # загрузить 0-символ для сравнения
    bne t2, t3, loop        # повторить итерацию, если символ не null

# Настроить параметры для вывода шестнадцатеричного числа,
# затем вызвать Linux
    sub a0, a1, t5      # получить длину путем вычитания указателей
    ret                 # вернуться к вызывающему элементу исходного кода
