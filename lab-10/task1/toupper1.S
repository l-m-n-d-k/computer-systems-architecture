#
# Базовая (неоптимизированная) функция, собранная по листингам 10.1-10.2
# пособия: фрагмент сравнения диапазона из листинга 10.2 вставлен в тот же
# каркас функции, что и в листинге 10.5 (листинги 10.1/10.2 сами по себе -
# это фрагмент с двумя ветвлениями, а не отдельный файл)
#
.global toupper
toupper:
    mv t5, a1            # сохранить исходную outstr для расчета длины

loop:
    lb t2, 0(a0)        # загрузить символ
    addi a0, a0, 1      # увеличить указатель буфера на 1

    # Если t2 > 'z', то перейти к cont
    li t3, 'z'               # загрузить 'z' для сравнения
    bgt t2, t3, cont    # ветвление, если буква > 'z'?

    # Иначе, если t2 < 'a', перейти в конец if
    li t3, 'a'               # загрузить 'а' для сравнения
    blt t2, t3, cont         # переход в конец, если не в нижнем регистре

    # если программа выполнилась до этого места, то буква в нижнем регистре
    addi t2, t2, ('A'-'a')
cont:
    # end if
    sb t2, 0(a1)        # сохранить символ в выходном строковом литерале
    addi a1, a1, 1      # увеличить буфер на 1 для следующего символа

    li t3, 0           # загрузить 0-символ для сравнения
    bne t2, t3, loop        # повторить итерацию, если символ не null

    sub a0, a1, t5      # получить длину путем вычитания указателей
    ret                 # вернуться к вызывающему элементу исходного кода
