#
# Функция на языке ассемблера для конвертации символов
# строкового литерала в верхний регистр.
#
# a0 - адрес входного строкового литерала
# a1 - адрес выходного строкового литерала
# t2 - текущий обрабатываемый символ
# t5 - исходный выходной строковый литерал для расчета длины строки
#

.global _start           # Точка входа для редактора связей
.macro toupper inputstr, outputstr
    la a0, \inputstr
    la a1, \outputstr
    mv t5, a1               # сохранить адрес исходной строки
                            # для расчета длины
# Цикл выполняется до тех пор, пока не будет встречен
# нулевой (null) символ
Loop:
    lb t2, 0(a0)        # загрузить символ
    addi a0, a0, 1      # увеличить указатель буфера на 1

    andi t2, t2, 0xdf   # очистить бит по адресу 0x20

    sb t2, 0(a1)           #   сохранить символ в выходном строковом литерале
    addi a1, a1, 1         # увеличить буфер для следующего символа на 1

    li t3, 0               # загрузить 0-символ для сравнения
    bne t2, t3, Loop            # повторить итерацию, если символ не равен null

    # Настроить параметры для вывода шестнадцатеричного числа
    # и затем вызвать Linux
    sub a0, a1, t5      #   получить длину путем вычитания указателей
.endm

_start:
.option push
.option norelax
    la gp, __global_pointer$
.option pop

    toupper instr, outstr

    # Настроить параметры для вывода результирующего строкового литерала
    # и затем вызвать Linux
    mv a2, a0                # Кодом возврата является длина строки
    li a0, 1                 # 1 = StdOut
    la a1, outstr            # выводимый строковый литерал
    li a7, 64                # системный вызов операции записи Linux
    ecall                    # вывести строковый литерал

    # Задать параметры для завершения работы программы
    # и вызвать Linux для завершения
    li a0, 0                 # Использовать код возврата
    li a7, 93                 # Код 93 служебной команды завершает программу
    ecall                    # завершить программу

.data
instr:
    .asciz "ThisIsRatherALargeVariableNameAaZz//['[\n"
outstr:
    .fill 255, 1, 0
